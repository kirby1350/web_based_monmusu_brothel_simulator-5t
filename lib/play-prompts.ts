/** 种族 play 的熟练档：看它对应的服务技能 / M、S 性；都没有时按「熟练」（天生就会） */
export function playTier(girl: MonstGirl, playId: string): Tier | undefined {
  const p = ALL_PLAYS.find((x) => x.id === playId)
  if (!p) return undefined
  if (p.source !== 'race') return getSkillRank(girl, p.source as SkillKey) as Tier | undefined
  const svc = p.match?.services?.find((s) => s !== '种族')
  if (svc) return (getSkillRank(girl, svc as SkillKey) as Tier | undefined) ?? '初学'
  const kind = p.match?.kinds?.find((k) => k === 'M' || k === 'S')
  if (kind) return (getSkillRank(girl, `${kind}性` as SkillKey) as Tier | undefined) ?? '初学'
  return '熟练'
}

const tierText = (e: CraftEntry, rank: SkillRank | Tier | undefined) =>
  rank ? `${rank}：${e.tiers[rank as Tier]}` : `未学：比初学还生涩，全凭本能——${e.tiers['初学']}`

/** 一个 play 的写作提示（一行半） */
export function playCraftLine(girl: MonstGirl, playId: string): string {
  const p = ALL_PLAYS.find((x) => x.id === playId)
  const e = PLAY_CRAFT[playId]
  if (!p || !e) return ''
  return `- 「${p.name}」（${girl.name}）：${e.essence}。感官：${e.sense}。${tierText(e, playTier(girl, playId))}`
}

/** 一项技能的写作提示 */
export function skillCraftLine(girl: MonstGirl, skill: SkillKey): string {
  const e = SKILL_CRAFT[skill]
  if (!e) return ''
  return `- ${skill}（${girl.name}）：${e.essence}。感官：${e.sense}。${tierText(e, getSkillRank(girl, skill))}`
}

/** 这一步用到的技能：迎客/挑逗看待客，前戏看手技，正戏看主类型（种族主需求不单列） */
export function stepSkill(stepIndex: number, mainSkill?: string): SkillKey | undefined {
  if (stepIndex === 0 || stepIndex === 1) return '待客'
  if (stepIndex === 2) return '手技'
  if (stepIndex === 3 && mainSkill && mainSkill !== '种族') return mainSkill as SkillKey
  return undefined
}

/** 内置种族流程这一步的展开（流程被改过的步不给） */
export function flowStepDetail(race: string | undefined, stepIndex: number): string {
  return (race && RACE_FLOW_DETAIL[race]?.[stepIndex]) || ''
}

export interface CraftInput {
  stepIndex: number
  girl: MonstGirl
  mainSkill?: string
  /** 挂在这一步的 play id */
  playIds: string[]
  /** 使用内置种族流程且这一步没被改过时的种族 */
  flowRace?: string
}

/** 【这一步怎么写】：步骤展开 + 种族流程细节 + 当前技能 + 这一步的 play；只给当前步骤 */
export function buildCraftBlock(c: CraftInput): string {
  const lines: string[] = []
  const how = STEP_HOW[c.stepIndex]
  if (how) lines.push(`- 写法：${how}`)
  const fd = flowStepDetail(c.flowRace, c.stepIndex)
  if (fd) lines.push(`- 这一步的种族细节：${fd}`)
  const sk = stepSkill(c.stepIndex, c.mainSkill)
  if (sk) lines.push(skillCraftLine(c.girl, sk))
  for (const id of c.playIds) lines.push(playCraftLine(c.girl, id))
  const body = lines.filter(Boolean)
  return body.length ? `【这一步怎么写（素材，化用而不要照抄）】\n${body.join('\n')}` : ''
}

/** 这一场用的是内置种族流程、且这一步的做法没被改过时，返回那个种族（否则 undefined） */
export function presetFlowRace(flow: { choice: string; actions: string[] } | undefined, stepIndex: number): string | undefined {
  const pf = flow ? PRESET_FLOWS.find((f) => f.id === flow.choice) : undefined
  return pf && pf.actions[stepIndex] === flow!.actions[stepIndex] ? pf.race : undefined
}

/** play 挂在哪一步：准备页定的 → 现场插入时的那一步 → 默认正戏 */
export function playStepOf(id: string, playSteps: Record<string, number> | undefined, insertedAt: Record<string, number> | undefined): number {
  return playSteps?.[id] ?? insertedAt?.[id] ?? 3
}
