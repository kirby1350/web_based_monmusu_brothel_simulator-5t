/** 【客人的声音】段 */
export function guestVoiceBlock(g: Guest): string {
  const lines: string[] = []
  const pv = PERSONALITY_VOICE[g.personality] ?? KEYWORD_VOICE.filter(([re]) => re.test(g.personality)).map(([, v]) => v).join('；')
  lines.push(`性格「${g.personality}」：${pv || '按他的性格自然说话，避免千篇一律的下流台词'}`)
  lines.push(CLASS_VOICE[g.guestClass ?? 'commoner'] ?? CLASS_VOICE.commoner)
  const demand = g.demand ?? 0
  if (demand >= 8) lines.push('挑剔的上等客（挑剔度高）：见惯了好东西，评头论足、拿别家比较，一点瑕疵都会指出来；称赞很少，但一旦出口就是真的满意——要让她靠真本事一点点赢得他的认可')
  else if (demand >= 4) lines.push('有点挑剔：会提要求、会纠正她，做得好时才给一句肯定')
  if (g.desireKind === 'M') lines.push('他想施虐：命令、按住、羞辱的话多，享受她的顺从与忍耐（强度仍按当前步骤上限）')
  else if (g.desireKind === 'S') lines.push('他想被榨：渴望被她主导，会求饶、会听话，被命令时反而更兴奋')
  const tv = g.traits.map((t) => TRAIT_VOICE[t]).filter(Boolean)
  if (tv.length) lines.push(...tv)
  lines.push(`他最想要的是「${getMainService(g)}」类的侍奉（${g.desires}）：话题和要求会不断绕回这里`)
  return `【客人的声音（${g.name}）】\n${lines.map((l) => `- ${l}`).join('\n')}\n- 他的说话完整度与节奏随【此刻的兴奋与快感】里他的档位变化；性格与身份的底色不变`
}
